//! Credential handles (arca-autofill.md §8): 16 random bytes that stand for
//! a value the app never sees. One per fill or typed entry, bound to the
//! field's parent (the recipient), for one submit, for at most 10 minutes.
//! Only a courier for that recipient may redeem one (A1).

use std::collections::HashMap;
use std::time::{Duration, Instant};

use arca_store::secret::LockedBuf;
use arca_store::{ItemId, Recipient};

pub type Handle = [u8; 16];

/// arca-autofill.md §8: a handle expires after 10 minutes.
pub const TTL: Duration = Duration::from_secs(600);
/// A field holds one handle at a time; this bounds a misbehaving UI.
pub const MAX: usize = 1024;

pub enum Source {
    /// A stored item, read at redeem time (so a lock in between voids it).
    Item(ItemId),
    /// Typed or generated, held only in memory.
    Pending(LockedBuf),
}

pub struct Entry {
    pub user: String,
    pub recipient: Recipient,
    pub source: Source,
    pub expires: Instant,
    /// Generated by Arca (offered for saving after a successful submit).
    pub generated: bool,
}

#[derive(Default)]
pub struct Handles {
    map: HashMap<Handle, Entry>,
}

impl Handles {
    fn sweep(&mut self, now: Instant) {
        self.map.retain(|_, e| e.expires > now);
    }

    /// A new handle for `e`. `None` when full.
    pub fn issue(&mut self, e: Entry) -> Option<Handle> {
        self.sweep(Instant::now());
        if self.map.len() >= MAX {
            return None;
        }
        let mut h = [0u8; 16];
        getrandom::getrandom(&mut h).ok()?;
        self.map.insert(h, e);
        Some(h)
    }

    pub fn drop_handle(&mut self, h: &Handle) {
        self.map.remove(h);
    }

    /// Redeem once, for exactly the recipient it was issued for. Anything
    /// else (unknown, expired, another recipient or user) is `None`, and a
    /// mismatch also burns the handle: a handle shown to the wrong party is
    /// treated as leaked.
    pub fn take(&mut self, h: &Handle, user: &str, recipient: &Recipient) -> Option<Entry> {
        let e = self.map.remove(h)?;
        if e.expires <= Instant::now() || e.user != user || &e.recipient != recipient {
            return None;
        }
        Some(e)
    }

    /// Lock: every pending value of `user` goes (handles to stored items
    /// would fail at redeem anyway, but drop them too).
    pub fn lock_user(&mut self, user: &str) {
        self.map.retain(|_, e| e.user != user);
    }

    pub fn len(&self) -> usize {
        self.map.len()
    }

    pub fn is_empty(&self) -> bool {
        self.map.is_empty()
    }
}
