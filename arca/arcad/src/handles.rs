//! Credential handles (arca-autofill.md §8): 16 random bytes that stand for
//! a value the app never sees. One per fill or typed entry, bound to the
//! field's parent (the recipient), for one submit, for at most 10 minutes.
//! Only a courier for that recipient may redeem one (A1).

use std::collections::HashMap;
use std::time::{Duration, Instant};

use arca_store::secret::LockedBuf;
use arca_store::{ItemId, Recipient};

pub type Handle = [u8; 16];

/// arca-autofill.md §8: a handle expires after 10 minutes.
pub const TTL: Duration = Duration::from_secs(600);
/// A field holds one handle at a time; this bounds a misbehaving UI.
pub const MAX: usize = 1024;
pub const HOLD_PRINT_PIN: u8 = 4;

pub enum Source {
    /// A stored item, read at redeem time (so a lock in between voids it).
    Item(ItemId),
    /// Typed or generated, held only in memory.
    Pending(LockedBuf),
}

pub struct Entry {
    pub user: String,
    pub persona: String,
    pub recipient: Recipient,
    pub source: Source,
    pub expires: Instant,
    /// Generated by Arca (offered for saving after a successful submit).
    pub generated: bool,
    /// What kind of field it was typed into, when that limits who may
    /// redeem it: 0 any, `HOLD_FOR_WIFI` only `take_wifi`, `HOLD_FOR_VPN` only `take_vpn`,
    /// `HOLD_FOR_RECOVERY` only `take_recovery`.
    pub hold: u8,
    /// SPKI digest and printer UUID for a per-job Arca PIN.
    pub printer: Option<([u8; 32], String)>,
}

#[derive(Default)]
pub struct Handles {
    map: HashMap<Handle, Entry>,
}

impl Handles {
    fn sweep(&mut self, now: Instant) {
        self.map.retain(|_, e| e.expires > now);
    }

    /// A new handle for `e`. `None` when full.
    pub fn issue(&mut self, e: Entry) -> Option<Handle> {
        self.sweep(Instant::now());
        if self.map.len() >= MAX {
            return None;
        }
        let mut h = [0u8; 16];
        getrandom::getrandom(&mut h).ok()?;
        self.map.insert(h, e);
        Some(h)
    }

    pub fn drop_handle(&mut self, h: &Handle) {
        self.map.remove(h);
    }

    /// Redeem once, for exactly the recipient it was issued for. Anything
    /// else (unknown, expired, another recipient or user) is `None`, and a
    /// mismatch also burns the handle: a handle shown to the wrong party is
    /// treated as leaked.
    pub fn take(&mut self, h: &Handle, user: &str, persona: &str, recipient: &Recipient) -> Option<Entry> {
        let e = self.map.remove(h)?;
        if e.hold != 0 || e.expires <= Instant::now() || e.user != user || e.persona != persona || &e.recipient != recipient {
            return None;
        }
        Some(e)
    }

    pub fn take_print_pin(&mut self, h: &Handle, user: &str, persona: &str, key: &[u8; 32], uuid: &str) -> Option<LockedBuf> {
        let e = self.map.remove(h)?;
        match e.source {
            Source::Pending(v) if e.hold == HOLD_PRINT_PIN && e.expires > Instant::now() && e.user == user && e.persona == persona
                && e.printer.as_ref().is_some_and(|(k, id)| k == key && id == uuid) => Some(v),
            _ => None,
        }
    }

    /// Redeem a Wi-Fi passphrase field's typed value, once, for the Wi-Fi
    /// key service (curia.md §4). Any other handle shown here is burned:
    /// the service has no business holding it.
    pub fn take_wifi(&mut self, h: &Handle) -> Option<LockedBuf> {
        let e = self.map.remove(h)?;
        match e.source {
            Source::Pending(v) if e.hold == crate::proto::op::HOLD_FOR_WIFI && e.expires > Instant::now() => Some(v),
            _ => None,
        }
    }

    /// Redeem a VPN sign-in field's typed value, once, for the crypta
    /// service (vpn.md §9.3). Any other handle shown here is burned.
    pub fn take_vpn(&mut self, h: &Handle) -> Option<LockedBuf> {
        let e = self.map.remove(h)?;
        match e.source {
            Source::Pending(v) if e.hold == crate::proto::op::HOLD_FOR_VPN && e.expires > Instant::now() => Some(v),
            _ => None,
        }
    }

    /// Redeem a stick recovery code typed into Arca's field, once, for
    /// `VK_ADOPT` as `user` (tessera-encryption.md §7.4). Any other handle
    /// shown here is burned.
    pub fn take_recovery(&mut self, h: &Handle, user: &str) -> Option<LockedBuf> {
        let e = self.map.remove(h)?;
        match e.source {
            Source::Pending(v) if e.hold == crate::proto::op::HOLD_FOR_RECOVERY && e.user == user && e.expires > Instant::now() => Some(v),
            _ => None,
        }
    }

    /// A typed value held for `from` (the broker's app), handed on to
    /// `to` (a web endpoint, persona `persona`): a new handle; the old one
    /// is spent either way.
    pub fn rebind(&mut self, h: &Handle, user: &str, from: &Recipient, persona: &str, to: Recipient) -> Option<Handle> {
        let e = self.map.remove(h)?;
        if e.hold != 0 || e.expires <= Instant::now() || e.user != user || &e.recipient != from || !matches!(e.source, Source::Pending(_)) {
            return None;
        }
        self.issue(Entry { persona: persona.into(), recipient: to, ..e })
    }

    /// The stored item a handle names, for exactly the party it was
    /// issued to, without redeeming it (FILL looks before it takes, so a
    /// fill that must wait for verification leaves its handles).
    pub fn item_of(&self, h: &Handle, user: &str, persona: &str, recipient: &Recipient) -> Option<ItemId> {
        let e = self.map.get(h)?;
        if e.hold != 0 || e.expires <= Instant::now() || e.user != user || e.persona != persona || &e.recipient != recipient {
            return None;
        }
        match e.source {
            Source::Item(id) => Some(id),
            Source::Pending(_) => None,
        }
    }

    /// Lock: every pending value of `user` goes (handles to stored items
    /// would fail at redeem anyway, but drop them too).
    pub fn lock_user(&mut self, user: &str) {
        self.map.retain(|_, e| e.user != user);
    }

    pub fn len(&self) -> usize {
        self.map.len()
    }

    pub fn is_empty(&self) -> bool {
        self.map.is_empty()
    }
}
