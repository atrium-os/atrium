//! Compile the GLSL triangles (atrium-gir/tests/shaders/tri.vert, tri.frag
//! and tri_color.vert, tri_color.frag) and print them as a C header for
//! si-client-test 22 and 23 (stages 7c, 7c-2): code words and the register
//! values the pipeline needs.
//!
//!     cargo run --example si_tri_glsl > ../atrium-gpu-amd/tests/si_tri_glsl.h

use atrium_rdna4_compiler::{compile, Binary};

fn build(name: &str) -> Binary {
    let bytes = std::fs::read(format!("{}/../atrium-gir/tests/shaders/{name}", env!("CARGO_MANIFEST_DIR"))).unwrap();
    let opts = atrium_spv_frontend::Options { native_subgroups: true, builtin_blocks: true, ..Default::default() };
    let m = atrium_spv_frontend::translate_with_options(&bytes, &opts).unwrap();
    let mut g = atrium_gir::build::build(&m, 0).unwrap();
    atrium_gir::passes::optimize(&mut g);
    compile(&g).unwrap_or_else(|e| panic!("{name}: {e:?}"))
}

fn words(name: &str, b: &Binary) -> String {
    let mut s = format!("static const uint32_t {name}[] = {{");
    for (i, w) in b.code.iter().enumerate() {
        s += if i % 6 == 0 { "\n\t" } else { " " };
        s += &format!("0x{w:08x},");
    }
    s + "\n};\n"
}

fn pair(p: &str, vs_file: &str, ps_file: &str) {
    let vs = build(vs_file);
    let ps = build(ps_file);
    let up = p.to_uppercase();
    println!("{}", words(&format!("{p}_vs"), &vs));
    println!("#define {up}_VS_VGPRS\t{}", vs.vgprs);
    println!("#define {up}_VS_USER_SGPRS\t{}\t/* [attribute ring descriptor x4,] base vertex, base instance, ... */", vs.abi.user_sgprs());
    println!("#define {up}_VS_PARAMS\t{}\t/* attribute ring parameters (locations {:?}) */", vs.vs_params.len(), vs.vs_params);
    println!("{}", words(&format!("{p}_ps"), &ps));
    println!("#define {up}_PS_VGPRS\t{}", ps.vgprs);
    println!("#define {up}_PS_USER_SGPRS\t{}", ps.abi.user_sgprs());
    println!("#define {up}_PS_INPUT_ENA\t{:#x}", ps.ps_input_ena);
    // SPI_PS_INPUT_CNTL_i: OFFSET (the VS parameter of that location),
    // FLAT_SHADE bit 10.
    let cntl: Vec<String> = ps.ps_inputs.iter().map(|(loc, interp)| {
        let off = vs.vs_params.iter().position(|l| l == loc).expect("PS input the VS does not write") as u32;
        let flat = if *interp == atrium_gir::Interp::Flat { 1u32 << 10 } else { 0 };
        format!("{:#x}", off | flat)
    }).collect();
    println!("#define {up}_PS_INPUTS\t{}", cntl.len());
    println!("static const uint32_t {p}_ps_input_cntl[] = {{ {} }};", if cntl.is_empty() { "0".to_string() } else { cntl.join(", ") });
    let exp: Vec<String> = ps.exports.iter().map(|(t, m)| format!("tgt {t} mask {m:#x}")).collect();
    println!("/* PS exports: {} */\n", exp.join(", "));
}

fn main() {
    println!("/* Generated by atrium-rdna4-compiler/examples/si_tri_glsl.rs from");
    println!(" * atrium-gir/tests/shaders/tri*.vert and tri*.frag (stages 7c, 7c-2): the");
    println!(" * 7b triangle compiled by our shader compiler, plain (glsl_*) and with");
    println!(" * a colour per vertex (color_*). Do not edit. */");
    pair("glsl", "tri.vert.spv", "tri.frag.spv");
    pair("color", "tri_color.vert.spv", "tri_color.frag.spv");
}
