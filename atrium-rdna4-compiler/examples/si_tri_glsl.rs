//! Compile the GLSL triangle (atrium-gir/tests/shaders/tri.vert, tri.frag)
//! and print it as a C header for si-client-test 22 (stage 7c): code words
//! and the register values the pipeline needs.
//!
//!     cargo run --example si_tri_glsl > ../atrium-gpu-amd/tests/si_tri_glsl.h

use atrium_rdna4_compiler::{compile, Binary};

fn build(name: &str) -> Binary {
    let bytes = std::fs::read(format!("{}/../atrium-gir/tests/shaders/{name}", env!("CARGO_MANIFEST_DIR"))).unwrap();
    let opts = atrium_spv_frontend::Options { native_subgroups: true, builtin_blocks: true, ..Default::default() };
    let m = atrium_spv_frontend::translate_with_options(&bytes, &opts).unwrap();
    let mut g = atrium_gir::build::build(&m, 0).unwrap();
    atrium_gir::passes::optimize(&mut g);
    compile(&g).unwrap_or_else(|e| panic!("{name}: {e:?}"))
}

fn words(name: &str, b: &Binary) -> String {
    let mut s = format!("static const uint32_t {name}[] = {{");
    for (i, w) in b.code.iter().enumerate() {
        s += if i % 6 == 0 { "\n\t" } else { " " };
        s += &format!("0x{w:08x},");
    }
    s + "\n};\n"
}

fn main() {
    let vs = build("tri.vert.spv");
    let ps = build("tri.frag.spv");
    println!("/* Generated by atrium-rdna4-compiler/examples/si_tri_glsl.rs from");
    println!(" * atrium-gir/tests/shaders/tri.vert and tri.frag (stage 7c): the 7b");
    println!(" * triangle, compiled by our shader compiler. Do not edit. */");
    println!("{}", words("glsl_vs", &vs));
    println!("#define GLSL_VS_VGPRS\t{}", vs.vgprs);
    println!("#define GLSL_VS_USER_SGPRS\t{}\t/* base vertex, base instance, ... */", vs.abi.user_sgprs());
    println!("{}", words("glsl_ps", &ps));
    println!("#define GLSL_PS_VGPRS\t{}", ps.vgprs);
    println!("#define GLSL_PS_USER_SGPRS\t{}", ps.abi.user_sgprs());
    println!("#define GLSL_PS_INPUT_ENA\t{:#x}", ps.ps_input_ena);
    let exp: Vec<String> = ps.exports.iter().map(|(t, m)| format!("tgt {t} mask {m:#x}")).collect();
    println!("/* PS exports: {} */", exp.join(", "));
}
