#!/usr/bin/env python3
"""Generate src/regs.rs from Linux's GFX12 register headers (AMD, MIT).

Usage: python3 -I gen/gen_regs.py spec/gc_12_0_0_offset.h.xz spec/gc_12_0_0_sh_mask.h.xz > src/regs.rs

Only the register groups the backend uses are emitted (PREFIXES). Add a prefix
and rerun rather than writing an offset by hand.
"""
import lzma, re, sys

PREFIXES = ("COMPUTE_",)

def read(p):
    return (lzma.open(p).read() if p.endswith('.xz') else open(p, 'rb').read()).decode()

off, mask = read(sys.argv[1]), read(sys.argv[2])
regs = {}
for m in re.finditer(r'#define reg(\w+?)\s+(0x[0-9a-fA-F]+)\s*$', off, re.M):
    name, val = m.group(1), int(m.group(2), 16)
    if name.endswith('_BASE_IDX') or not name.startswith(PREFIXES):
        continue
    base = re.search(rf'#define reg{name}_BASE_IDX\s+(\d+)', off)
    regs[name] = (val, int(base.group(1)) if base else 0)
fields = {}
for m in re.finditer(r'#define (\w+?)__(\w+?)__SHIFT\s+(0x[0-9a-fA-F]+)', mask):
    reg, fld, sh = m.group(1), m.group(2), int(m.group(3), 16)
    if reg not in regs:
        continue
    mk = re.search(rf'#define {reg}__{fld}_MASK\s+(0x[0-9a-fA-FL]+)', mask)
    fields.setdefault(reg, []).append((fld, sh, int(mk.group(1).rstrip('L'), 16)))

print('// @generated by gen/gen_regs.py from Linux drivers/gpu/drm/amd/include/asic_reg/gc/')
print('// gc_12_0_0_{offset,sh_mask}.h (Copyright Advanced Micro Devices, Inc.; MIT). Do not edit.')
print('#![allow(missing_docs, non_upper_case_globals, dead_code)]')
print('/// A register: dword offset within its GC segment, and the segment index.')
print('#[derive(Clone, Copy, Debug, PartialEq, Eq)]')
print('pub struct Reg { pub offset: u32, pub base_idx: u32 }')
for name, (val, b) in sorted(regs.items(), key=lambda x: x[1]):
    print(f'pub const {name}: Reg = Reg {{ offset: 0x{val:x}, base_idx: {b} }};')
for reg, fl in sorted(fields.items()):
    print(f'pub mod {reg.lower()} {{')
    for fld, sh, mk in fl:
        print(f'    pub const {fld}_SHIFT: u32 = {sh};')
        print(f'    pub const {fld}_MASK: u32 = 0x{mk:x};')
    print('}')
