//! The trusted chrome's glyphs (src/chrome.rs): IBM Plex Mono rasterized
//! here, at build time, into coverage tables, for exactly the characters
//! an origin may hold. frescod parses no font file at run time.
//!
//! One table per scale the chrome may draw at (resolution-independence.md
//! §8): the strip and its text are in points, so a 2.0 monitor gets the
//! glyphs rasterized at 28 px, not 14 px blown up.

use std::fmt::Write;

/// Size of the chrome's text in points (pixels at scale 1.0).
const SIZE: f32 = 14.0;
/// The scales a table is made for, in thousandths: quarter steps from 1.0
/// to 4.0, the range a monitor's scale takes. The chrome draws with the
/// largest table not above its scale.
const SCALES: &[u32] = &[1000, 1250, 1500, 1750, 2000, 2250, 2500, 2750, 3000, 3250, 3500, 3750, 4000];
/// Must match `fresco_split::chrome::origin_char`.
const CHARS: &[u8] = b"abcdefghijklmnopqrstuvwxyz0123456789.:/-[]_";

fn main() {
    let font = "../fonts/ibm-plex/IBMPlexMono-Regular.ttf";
    println!("cargo:rerun-if-changed={font}");
    println!("cargo:rerun-if-changed=build.rs");
    let data = std::fs::read(font).expect("IBM Plex Mono");
    let f = swash::FontRef::from_index(&data, 0).expect("a font");
    let mut ctx = swash::scale::ScaleContext::new();
    let mut out = String::new();
    writeln!(out, "/// Generated by build.rs from IBM Plex Mono {SIZE} pt.").unwrap();
    writeln!(out, "/// (char, left, top above the baseline, width, height, coverage rows)").unwrap();
    writeln!(out, "pub type Glyph = (u8, i32, i32, u32, u32, &'static [u8]);").unwrap();
    writeln!(out, "pub struct Font {{ pub scale_milli: u32, pub advance: i32, pub ascent: i32, pub line: i32, pub glyphs: &'static [Glyph] }}").unwrap();
    writeln!(out, "pub const FONTS: &[Font] = &[").unwrap();
    for &scale in SCALES {
        let size = SIZE * scale as f32 / 1000.0;
        let mut scaler = ctx.builder(f).size(size).hint(true).build();
        let metrics = f.metrics(&[]).scale(size);
        let gm = f.glyph_metrics(&[]).scale(size);
        let advance = gm.advance_width(f.charmap().map('a'));
        writeln!(out, "  Font {{ scale_milli: {scale}, advance: {}, ascent: {}, line: {}, glyphs: &[",
            advance.round() as i32, metrics.ascent.round() as i32, (metrics.ascent + metrics.descent).round() as i32).unwrap();
        for &c in CHARS {
            let gid = f.charmap().map(c as char);
            let img = swash::scale::Render::new(&[swash::scale::Source::Outline])
                .format(swash::zeno::Format::Alpha)
                .render(&mut scaler, gid)
                .expect("a glyph");
            let p = img.placement;
            writeln!(out, "    ({c}, {}, {}, {}, {}, &{:?}),", p.left, p.top, p.width, p.height, img.data).unwrap();
        }
        writeln!(out, "  ] }},").unwrap();
    }
    writeln!(out, "];").unwrap();
    let dst = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("chrome_glyphs.rs");
    std::fs::write(dst, out).unwrap();
}
