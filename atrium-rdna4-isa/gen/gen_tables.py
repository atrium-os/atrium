#!/usr/bin/env python3
"""Generate src/tables.rs from AMD's machine-readable RDNA4 ISA XML.

Usage: python3 -I gen/gen_tables.py spec/amdgpu_isa_rdna4.xml.xz > src/tables.rs

The XML is AMD's (MIT). Nothing in tables.rs is written by hand: rerun this
script when AMD publishes a new XML and commit both files together.
"""
import lzma, sys, xml.etree.ElementTree as ET

src = sys.argv[1]
data = lzma.open(src).read() if src.endswith('.xz') else open(src, 'rb').read()
root = ET.fromstring(data)
doc = root.find('Document')
isa = root.find('ISA')

def b2i(s):
    s = (s or '').strip()
    return int(s, 2) if s else 0

encs = []
enc_index = {}
for e in isa.find('Encodings'):
    name = e.findtext('EncodingName')
    bits = int(e.findtext('BitCount'))
    mask = b2i(e.findtext('EncodingIdentifierMask'))
    ids = [b2i(i.text) for i in e.find('EncodingIdentifiers')]
    fields = []
    bm = e.find('MicrocodeFormat/BitMap')
    for f in (bm if bm is not None else []):
        ranges = [(int(r.findtext('BitOffset')), int(r.findtext('BitCount')))
                  for r in sorted(f.find('BitLayout'), key=lambda r: int(r.get('Order')))]
        fields.append((f.findtext('FieldName'), ranges))
    enc_index[name] = len(encs)
    encs.append(dict(name=name, order=int(e.get('Order')), bits=bits, mask=mask, ids=ids, fields=fields))

insts = []
for i in isa.find('Instructions'):
    name = i.findtext('InstructionName')
    fl = i.find('InstructionFlags')
    flags = 0
    for bit, tag in enumerate(['IsBranch', 'IsConditionalBranch', 'IsIndirectBranch',
                               'IsProgramTerminator', 'IsImmediatelyExecuted']):
        if (fl.findtext(tag) or '').strip().upper() == 'TRUE':
            flags |= 1 << bit
    group = i.findtext('FunctionalGroup/Name') or ''
    subgroup = i.findtext('FunctionalGroup/FunctionalSubgroups/Subgroup') or ''
    ies = []
    for ie in i.find('InstructionEncodings'):
        en = ie.findtext('EncodingName')
        if en not in enc_index:
            continue
        ops = []
        ops_el = ie.find('Operands')
        for o in (list(ops_el) if ops_el is not None else []):
            ops.append((o.findtext('FieldName') or '', o.findtext('OperandType') or '',
                        int(o.findtext('OperandSize') or 0),
                        o.get('Input') == 'true', o.get('Output') == 'true', o.get('IsImplicit') == 'true'))
        ies.append((enc_index[en], ie.findtext('EncodingCondition'), int(ie.findtext('Opcode')), ops))
    insts.append(dict(name=name, flags=flags, group=group, subgroup=subgroup, encodings=ies))

def rs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

out = []
w = out.append
w('// @generated by gen/gen_tables.py from AMD\'s machine-readable ISA. Do not edit.')
w(f'// Source: {doc.findtext("Copyright")} License: {doc.findtext("License")}.')
w(f'// Release date {doc.findtext("ReleaseDate")}, schema {doc.findtext("SchemaVersion")}.')
w('#![allow(clippy::all)]')
w('use crate::{EncodingDef, FieldDef, InstDef, InstEncodingDef, OperandDef};')
w('/// Release date of the AMD XML these tables were generated from.')
w(f'pub const ISA_RELEASE: &str = {rs(doc.findtext("ReleaseDate"))};')
w('/// Every encoding (microcode format).')
w('pub static ENCODINGS: &[EncodingDef] = &[')
for e in encs:
    fields = ', '.join(f'FieldDef {{ name: {rs(n)}, ranges: &[{", ".join(f"({o}, {c})" for o, c in r)}] }}' for n, r in e['fields'])
    ids = ', '.join(f'0x{x:x}' for x in e['ids'])
    w(f'    EncodingDef {{ name: {rs(e["name"])}, order: {e["order"]}, bits: {e["bits"]}, '
      f'id_mask: 0x{e["mask"]:x}, ids: &[{ids}], fields: &[{fields}] }},')
w('];')
w('/// Every instruction.')
w('pub static INSTRUCTIONS: &[InstDef] = &[')
for i in insts:
    encs_s = []
    for ei, cond, opc, ops in i['encodings']:
        ops_s = ', '.join(f'OperandDef {{ field: {rs(f)}, kind: {rs(t)}, size: {s}, input: {str(a).lower()}, output: {str(b).lower()}, implicit: {str(c).lower()} }}'
                          for f, t, s, a, b, c in ops)
        encs_s.append(f'InstEncodingDef {{ encoding: {ei}, condition: {rs(cond)}, opcode: {opc}, operands: &[{ops_s}] }}')
    w(f'    InstDef {{ name: {rs(i["name"])}, flags: {i["flags"]}, group: {rs(i["group"])}, subgroup: {rs(i["subgroup"])}, encodings: &[{", ".join(encs_s)}] }},')
w('];')
print('\n'.join(out))
