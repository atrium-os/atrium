#!/usr/bin/env python3
"""Writes src/presets.txt, the preset shape geometries in a compact form,
from ECMA-376's presetShapeDefinitions.xml (as Apache POI ships it, under
Apache-2.0: poi/src/main/resources/org/apache/poi/sl/draw/geom/).

  python3 tools/gen_presets.py presetShapeDefinitions.xml > src/presets.txt

Format, one item per line:
  =name                 a shape
  a NAME FMLA           an adjust value's default (avLst)
  r L T R B             the text rectangle (guide names or numbers)
  h R1 MIN1 MAX1 R2 MIN2 MAX2 X Y
                        an adjust handle at (X, Y): the adjust values it
                        moves with their ranges (- for none); for ahXY
                        across then down, for ahPolar radius then angle
  g NAME FMLA           a guide (gdLst)
  p W H FILL STROKE     a path: its own size (0: the shape's), fill
                        (n norm, - none, l lighten, L lightenLess, d darken,
                        D darkenLess), stroke (1/0)
  M x y | L x y | A wR hR stAng swAng | Q x1 y1 x y | C x1 y1 x2 y2 x y | Z
"""
import sys
import xml.etree.ElementTree as E

NS = '{http://schemas.openxmlformats.org/drawingml/2006/main}'
FILL = {None: 'n', 'norm': 'n', 'none': '-', 'lighten': 'l', 'lightenLess': 'L', 'darken': 'd', 'darkenLess': 'D'}


def pt(e):
    p = e.find(NS + 'pt')
    return [p.get('x'), p.get('y')]


def main():
    root = E.parse(sys.argv[1]).getroot()
    out = ['# Generated by tools/gen_presets.py from ECMA-376 presetShapeDefinitions.xml (Apache POI copy, Apache-2.0).']
    for shape in root:
        out.append('=' + shape.tag)
        for kind, tag in (('a', 'avLst'), ('g', 'gdLst')):
            lst = shape.find(NS + tag)
            if lst is None:
                continue
            for gd in lst.findall(NS + 'gd'):
                out.append(f"{kind} {gd.get('name')} {gd.get('fmla')}")
        rect = shape.find(NS + 'rect')
        if rect is not None:
            out.append('r ' + ' '.join(rect.get(k, '0') for k in ('l', 't', 'r', 'b')))
        ah = shape.find(NS + 'ahLst')
        if ah is not None:
            for h in ah:
                t = h.tag.replace(NS, '')
                keys = (('gdRefX', 'minX', 'maxX'), ('gdRefY', 'minY', 'maxY')) if t == 'ahXY' else (('gdRefR', 'minR', 'maxR'), ('gdRefAng', 'minAng', 'maxAng'))
                f = []
                for ref, lo, hi in keys:
                    if h.get(ref):
                        f += [h.get(ref), h.get(lo, '0'), h.get(hi, '0')]
                    else:
                        f += ['-', '-', '-']
                p = h.find(NS + 'pos')
                out.append('h ' + ' '.join(f + [p.get('x'), p.get('y')]))
        pl = shape.find(NS + 'pathLst')
        if pl is None:
            continue
        for path in pl.findall(NS + 'path'):
            stroke = '0' if path.get('stroke') in ('false', '0') else '1'
            out.append(f"p {path.get('w', '0')} {path.get('h', '0')} {FILL[path.get('fill')]} {stroke}")
            for c in path:
                t = c.tag.replace(NS, '')
                if t == 'moveTo':
                    out.append('M ' + ' '.join(pt(c)))
                elif t == 'lnTo':
                    out.append('L ' + ' '.join(pt(c)))
                elif t == 'arcTo':
                    out.append(f"A {c.get('wR')} {c.get('hR')} {c.get('stAng')} {c.get('swAng')}")
                elif t == 'quadBezTo':
                    out.append('Q ' + ' '.join(sum((list(map(str, [p.get('x'), p.get('y')])) for p in c.findall(NS + 'pt')), [])))
                elif t == 'cubicBezTo':
                    out.append('C ' + ' '.join(sum((list(map(str, [p.get('x'), p.get('y')])) for p in c.findall(NS + 'pt')), [])))
                elif t == 'close':
                    out.append('Z')
    print('\n'.join(out))


main()
