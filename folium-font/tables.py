#!/usr/bin/env python3
"""Regenerate src/tables.rs (encodings and the Adobe Glyph List) from
fontTools: python3 -I tables.py > src/tables.rs"""
from fontTools import agl
from fontTools.encodings.StandardEncoding import StandardEncoding

def names_for(codec):
    out = []
    for b in range(256):
        try:
            u = bytes([b]).decode(codec)
        except UnicodeDecodeError:
            out.append(None)
            continue
        out.append(None if b < 32 else agl.UV2AGL.get(ord(u)))
    return out

win = names_for('cp1252')
# ISO 32000-2 Annex D: 0xA0 is space, 0xAD hyphen, unused codes a bullet.
win[0xA0] = 'space'; win[0xAD] = 'hyphen'
for b in (0x7f, 0x81, 0x8d, 0x8f, 0x90, 0x9d):
    win[b] = 'bullet'
mac = names_for('mac_roman')
mac[0xCA] = 'space'
std = [None if n in ('.notdef', None) else n for n in StandardEncoding]

def arr(name, a):
    s = f"pub static {name}: [Option<&str>; 256] = [\n"
    for i in range(0, 256, 8):
        s += "    " + ", ".join("None" if n is None else f'Some("{n}")' for n in a[i:i + 8]) + ",\n"
    return s + "];\n\n"

src = "//! Generated by tables.py from fontTools 4.68 (MIT): the Adobe Glyph List\n//! (BSD-3, Adobe) and the standard encodings. Do not edit.\n\n"
src += arr("STANDARD", std) + arr("WIN_ANSI", win) + arr("MAC_ROMAN", mac)
src += "/// Glyph name to Unicode, sorted by name, first code point of each.\npub static AGL: &[(&str, u32)] = &[\n"
for n, u in sorted(agl.LEGACY_AGL2UV.items()):
    u = u if isinstance(u, int) else u[0]
    src += f'    ("{n}", 0x{u:04X}),\n'
src += "];\n"
print(src, end="")
