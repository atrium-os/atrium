/*
 * fresco.ko — FreeBSD newbus driver for the Fresco GPU transport.
 *
 * Attaches to the ivshmem-doorbell PCI device (vendor 0x1af4, device
 * 0x1110) exposed by our modified QEMU. Exposes /dev/fresco0 with:
 *   - mmap of BAR2 (16 MiB shmem) for the command/completion/input
 *     rings + CAS staging area
 *   - kqueue EVFILT_READ that wakes when the host advances the
 *     completion or input ring's write pointer. Implemented via a
 *     1 ms kernel callout (NOT MSI-X) — see "polling" note below.
 *   - ioctls for ringing the doorbell back at the host and reading
 *     diagnostic counters
 *
 * Why polling, not MSI-X:
 *   FreeBSD on qemu's `virt` machine under HVF cannot allocate MSI-X
 *   for late-attaching PCI devices. The IORT generated by qemu for
 *   gic-version=2 is empty, and forcing FDT mode (acpi=off) breaks
 *   boot (no event timer). Disabling ACPI is a non-starter, and
 *   patching qemu/FreeBSD's IORT generation is out of scope.
 *   ivshmem-doorbell only delivers via MSI-X, so we sidestep the
 *   doorbell entirely: we mirror the host's "1 ms poll timer"
 *   workaround on the guest side. Cost is ~0.1% CPU at idle.
 *
 * No DRM, no linuxkpi, no GPU-vendor abstraction. The transport is
 * generic shmem; the GPU API lives entirely in userspace, defined by
 * the Fresco wire protocol (reference server implementation lives at
 * ~/src/karythra-gpu-server, originally named for its first consumer).
 */

