//! bench-script > bench-r9700.sh: one self-contained shell script that times
//! the desktop shaders on the R9700 twice, compiled by our backend (through
//! amdgpu_runner, GPU timestamps around the dispatch) and by the system
//! Vulkan driver (vk_bench, RADV), on identical inputs generated on the box,
//! checks that both produce the same buffers, and appends RADV's own shader
//! dump (ACO disassembly and statistics) for comparison.
use atrium_rdna4_oracle::{b64, bench};
use std::fmt::Write as _;

fn main() {
    let src = |s: &str, name: &str| format!("cat > {name} <<'ATRIUM_EOF'\n{s}ATRIUM_EOF\n");
    let mut sh = String::from("#!/bin/sh\n# Atrium RDNA4 vs RADV timing (generated by atrium-rdna4-oracle bench-script).\nset -e\nW=$(mktemp -d)\ncd \"$W\"\n");
    sh += &src(include_str!("../../runner/amdgpu_runner.c"), "amdgpu_runner.c");
    sh += &src(include_str!("../../runner/vk_bench.c"), "vk_bench.c");
    sh += &src(include_str!("../../runner/bench_tool.c"), "bench_tool.c");
    sh += r#"cc -O2 -o amdgpu_runner amdgpu_runner.c 2>/dev/null
cc -O2 -o bench_tool bench_tool.c
VKINC=
if [ ! -f /usr/include/vulkan/vulkan.h ]; then
  mkdir -p vkdeb
  (cd vkdeb && apt-get download libvulkan-dev >/dev/null 2>&1 && dpkg-deb -x libvulkan-dev_*.deb x) && VKINC=-Ivkdeb/x/usr/include
fi
VKLIB=-lvulkan
[ -e /usr/lib/x86_64-linux-gnu/libvulkan.so ] || VKLIB=-l:libvulkan.so.1
HAVE_VK=0
if cc -O2 $VKINC -o vk_bench vk_bench.c $VKLIB; then HAVE_VK=1; else echo "NOTE: vk_bench did not build (Vulkan headers or loader missing); RADV runs skipped"; fi
DEV=
for n in /dev/dri/renderD*; do [ "$(cat /sys/class/drm/$(basename $n)/device/vendor 2>/dev/null)" = 0x1002 ] && DEV=$n && break; done
echo '=== atrium rdna4 vs radv bench ==='
uname -srm
echo "render node: $DEV"
cat /sys/class/drm/card*/device/product_name 2>/dev/null | head -1 || true
cat /sys/class/drm/card*/device/power_dpm_force_performance_level 2>/dev/null | head -1 || true
for f in mem_info_vram_total mem_info_vis_vram_total mem_info_gtt_total; do echo "$f=$(cat /sys/class/drm/card*/device/$f 2>/dev/null | head -1)"; done
dpkg-query -W -f='mesa-vulkan-drivers ${Version}\n' mesa-vulkan-drivers 2>/dev/null || true
"#;
    let benches = bench::all();
    for b in &benches {
        let n = &b.name;
        writeln!(sh, "mkdir -p {n}").unwrap();
        for (file, data) in [("code.in", &b.code), ("shader.spv", &b.spv)] {
            writeln!(sh, "base64 -d > {n}/{file} <<'ATRIUM_EOF'\n{}\nATRIUM_EOF", b64(data)).unwrap();
        }
        writeln!(sh, "cat > {n}/job.txt <<'ATRIUM_EOF'\n{}ATRIUM_EOF", b.job).unwrap();
        writeln!(sh, "cat > {n}/bench.txt <<'ATRIUM_EOF'\n{}ATRIUM_EOF", b.vk).unwrap();
        writeln!(sh, "echo \"--- {n} (ours: {} dwords, {} VGPRs, {} SGPRs)\"", b.stats.0, b.stats.1, b.stats.2).unwrap();
        writeln!(sh, "echo \"glyphs=$(./bench_tool gen {} {} {n})\"", b.kind, b.nodes).unwrap();
        writeln!(sh, "./amdgpu_runner {n} $DEV >/dev/null 2>&1 || true; echo '[atrium]'; grep -v '^gpu_ns=\\|^gc_base\\|^device' {n}/result.txt || true").unwrap();
        writeln!(sh, "if [ $HAVE_VK = 1 ]; then ./vk_bench {n} >/dev/null 2>&1 || true; echo '[radv]'; grep -v '^gpu_ns=' {n}/vk_result.txt || true").unwrap();
        // Same results from both drivers?
        writeln!(sh, "  c=$(od -An -tu4 -N4 {n}/counter.out | tr -d ' '); cv=$(od -An -tu4 -N4 {n}/counter.vk 2>/dev/null | tr -d ' '); echo \"counter atrium=$c radv=$cv\"").unwrap();
        writeln!(sh, "  [ -f {n}/instances.vk ] && echo \"instances: $(./bench_tool cmp {n}/instances.out {n}/instances.vk $((c * {})) {})\"", b.record, b.record).unwrap();
        writeln!(sh, "  [ -f {n}/scene.vk ] && echo \"scene: $(./bench_tool cmp {n}/scene.out {n}/scene.vk {})\"", 16 + 64 * b.nodes as u64).unwrap();
        writeln!(sh, "fi; true").unwrap();
        // Large outputs are only needed for the comparison.
        if b.nodes > 1 << 14 {
            writeln!(sh, "rm -f {n}/*.out {n}/*.vk {n}/*.in").unwrap();
        }
    }
    sh += "echo '=== RADV shader dumps (RADV_DEBUG=shaders,shaderstats) ==='\n";
    for b in benches.iter().filter(|b| b.nodes <= 1 << 14) {
        let n = &b.name;
        writeln!(sh, "if [ $HAVE_VK = 1 ]; then echo '--- aco {n}'; sed -i 's/^repeat .*/repeat 1/' {n}/bench.txt; RADV_DEBUG=shaders,shaderstats,nocache MESA_SHADER_CACHE_DISABLE=1 ./vk_bench {n} 2>&1 | grep -v '^$' | head -3000; fi").unwrap();
    }
    sh += "echo '=== end ==='\n";
    print!("{sh}");
}
