//! bundle-jobs > run-r9700.sh: one self-contained shell script that recreates
//! every case's job directory and the runner source, builds the runner, runs
//! all cases on the GPU, and prints a compact report (status, timing, gc_base,
//! and a hash plus the first words of every readback buffer) to paste back.
use std::fmt::Write as _;
use std::fs;

use atrium_rdna4_oracle::b64;

fn main() {
    let tmp = std::env::temp_dir().join(format!("rdna4-bundle-{}", std::process::id()));
    let runner = include_str!("../../runner/amdgpu_runner.c");
    let mut sh = String::from("#!/bin/sh\n# Atrium RDNA4 oracle jobs (generated by atrium-rdna4-oracle bundle-jobs).\nset -e\nW=$(mktemp -d)\ncd \"$W\"\n");
    writeln!(sh, "cat > amdgpu_runner.c <<'ATRIUM_EOF'\n{runner}ATRIUM_EOF").unwrap();
    sh += "cc -O2 -o amdgpu_runner amdgpu_runner.c\n";
    let mut cases = atrium_rdna4_oracle::cases::all();
    cases.extend(atrium_rdna4_oracle::cases::calibration());
    for c in &cases {
        let d = tmp.join(&c.name);
        c.write_job(&d).unwrap();
        writeln!(sh, "mkdir -p {}", c.name).unwrap();
        for e in fs::read_dir(&d).unwrap() {
            let e = e.unwrap();
            let name = e.file_name().into_string().unwrap();
            writeln!(sh, "base64 -d > {}/{} <<'ATRIUM_EOF'\n{}\nATRIUM_EOF", c.name, name, b64(&fs::read(e.path()).unwrap())).unwrap();
        }
    }
    sh += "DEV=\nfor n in /dev/dri/renderD*; do [ \"$(cat /sys/class/drm/$(basename $n)/device/vendor 2>/dev/null)\" = 0x1002 ] && DEV=$n && break; done\n";
    sh += "echo '=== atrium rdna4 oracle report ==='\nuname -srm\necho \"render node: $DEV\"\n";
    sh += "cat /sys/class/drm/card*/device/product_name 2>/dev/null | head -1 || true\n";
    for c in &cases {
        writeln!(sh, "echo \"--- {n}\"; ./amdgpu_runner {n} $DEV || true; cat {n}/result.txt", n = c.name).unwrap();
        // The readback BO can be larger than the expectation (page-rounded
        // sizes); compare only the expected prefix, as `Case::check` does.
        writeln!(sh, "for f in {n}/*.out; do [ -f \"$f\" ] || continue; echo \"$f sha256=$(sha256sum < $f | cut -c1-16)\"; od -An -tx4 -N64 \"$f\"; \
b=${{f%.out}}; [ -f \"$b.expect\" ] || continue; head -c $(wc -c < \"$b.expect\") \"$f\" > \"$b.cut\"; \
if [ -f \"$b.unordered\" ]; then r=$(cat \"$b.unordered\"); \
if [ \"$(od -An -v -tx1 -w$r \"$b.cut\" | sort)\" = \"$(od -An -v -tx1 -w$r \"$b.expect\" | sort)\" ]; then echo MATCH unordered; else echo MISMATCH unordered; od -An -tx4 -N256 \"$f\"; fi; \
elif cmp -s \"$b.cut\" \"$b.expect\"; then echo MATCH; else echo MISMATCH; cmp \"$b.cut\" \"$b.expect\" | head -1; od -An -tx4 -N256 \"$f\"; fi; done", n = c.name).unwrap();
    }
    sh += "echo '=== end ==='\n";
    print!("{sh}");
    let _ = fs::remove_dir_all(&tmp);
}
