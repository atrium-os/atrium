//! kmod_write42: the `write_42` oracle case at the kernel driver's GART
//! addresses, as a C header for atrium-gpu-amd's stage 4e first dispatch
//! (mes12.c). Regenerate with
//!
//!     cargo run -q --example kmod_write42 > ../atrium-gpu-amd/write42_ib.h
//!
//! The addresses must match DISP_GART_VA + DISP_CODE / DISP_OUT there
//! (the kmod checks them at run time).
//!
//! Stage 5b adds two IBs for a per-client VM (VMID 1, its own page table):
//! `w42_ib_vm` at VM_CODE_VA / VM_DATA_VA, and `w42_ib_vmx`, the same
//! shader told to write at VMX_DATA_VA, a VA mapped only in VMID 0 (the
//! GART: the 5b test's victim page). The shader is the same code at any VA.
//!
//! Stage 5c adds `w42_ib_uq` for a MES user queue's own VM: shader at
//! UQ_CODE_VA, output at UQ_DATA_VA (both processes use the same VAs).
use atrium_rdna4_oracle::cases::{write_42_at, IB_OFFSET};


const CODE_VA: u64 = 0x43000;
const DATA_VA: u64 = 0x45000;
const VM_CODE_VA: u64 = 0x1_0000_0000;
const VM_DATA_VA: u64 = 0x1_0010_0000;
const VMX_DATA_VA: u64 = 0x53000;
const UQ_CODE_VA: u64 = 0x2_0000_3000;
const UQ_DATA_VA: u64 = 0x2_0000_5000;

/// (shader dwords, IB dwords) of write_42 built at these addresses.
fn build(code_va: u64, data_va: u64) -> (Vec<u32>, Vec<u32>) {
    let c = write_42_at(code_va, data_va);
    let code = &c.buffers[0].init;
    let n = IB_OFFSET as usize / 4 + c.ib.2 as usize;
    let dw: Vec<u32> = code[..n * 4].chunks(4).map(|b| u32::from_le_bytes(b.try_into().unwrap())).collect();
    let shader_dw = dw[..IB_OFFSET as usize / 4].iter().rposition(|&d| d != 0).map_or(0, |i| i + 1);
    (dw[..shader_dw].to_vec(), dw[IB_OFFSET as usize / 4..].to_vec())
}

fn main() {
    let (shader, ib) = build(CODE_VA, DATA_VA);
    let (vm_shader, ib_vm) = build(VM_CODE_VA, VM_DATA_VA);
    let (vmx_shader, ib_vmx) = build(VM_CODE_VA, VMX_DATA_VA);
    let (uq_shader, ib_uq) = build(UQ_CODE_VA, UQ_DATA_VA);
    assert!(shader == vm_shader && shader == vmx_shader && shader == uq_shader, "shader depends on its VA");
    assert!(ib.len() == ib_vm.len() && ib.len() == ib_vmx.len() && ib.len() == ib_uq.len());
    let ib_dw = ib.len();
    println!("/* Generated by atrium-rdna4-oracle/examples/kmod_write42.rs; do not edit. */");
    println!("/* write_42: 64 threads (wave32) store 42 at out[i]. */");
    println!("#define W42_CODE_VA\t{CODE_VA:#x}ull");
    println!("#define W42_DATA_VA\t{DATA_VA:#x}ull");
    println!("#define W42_VM_CODE_VA\t{VM_CODE_VA:#x}ull");
    println!("#define W42_VM_DATA_VA\t{VM_DATA_VA:#x}ull");
    println!("#define W42_VMX_DATA_VA\t{VMX_DATA_VA:#x}ull");
    println!("#define W42_UQ_CODE_VA\t{UQ_CODE_VA:#x}ull");
    println!("#define W42_UQ_DATA_VA\t{UQ_DATA_VA:#x}ull");
    println!("#define W42_IB_OFFSET\t{IB_OFFSET:#x}u");
    println!("#define W42_IB_DW\t{ib_dw}u");
    println!("#define W42_OUT_DW\t64u");
    println!("#define W42_OUT_VALUE\t42u");
    let p = |name: &str, d: &[u32]| {
        println!("static const uint32_t {name}[{}] = {{", d.len());
        for ch in d.chunks(6) {
            println!("\t{},", ch.iter().map(|x| format!("{x:#010x}")).collect::<Vec<_>>().join(", "));
        }
        println!("}};");
    };
    p("w42_shader", &shader);
    p("w42_ib", &ib);
    p("w42_ib_vm", &ib_vm);
    p("w42_ib_vmx", &ib_vmx);
    p("w42_ib_uq", &ib_uq);
}
