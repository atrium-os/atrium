//! kmod_write42: the `write_42` oracle case at the kernel driver's GART
//! addresses, as a C header for atrium-gpu-amd's stage 4e first dispatch
//! (mes12.c). Regenerate with
//!
//!     cargo run -q --example kmod_write42 > ../atrium-gpu-amd/write42_ib.h
//!
//! The addresses must match DISP_GART_VA + DISP_CODE / DISP_OUT there
//! (the kmod checks them at run time).
use atrium_rdna4_oracle::cases::{write_42_at, IB_OFFSET};

const CODE_VA: u64 = 0x43000;
const DATA_VA: u64 = 0x45000;

fn main() {
    let c = write_42_at(CODE_VA, DATA_VA);
    let code = &c.buffers[0].init;
    let ib_dw = c.ib.2;
    let n = IB_OFFSET as usize / 4 + ib_dw as usize;
    let dw: Vec<u32> = code[..n * 4].chunks(4).map(|b| u32::from_le_bytes(b.try_into().unwrap())).collect();
    let shader_dw = dw[..IB_OFFSET as usize / 4].iter().rposition(|&d| d != 0).map_or(0, |i| i + 1);
    println!("/* Generated by atrium-rdna4-oracle/examples/kmod_write42.rs; do not edit. */");
    println!("/* write_42: 64 threads (wave32) store 42 at out[i]. */");
    println!("#define W42_CODE_VA\t{CODE_VA:#x}ull");
    println!("#define W42_DATA_VA\t{DATA_VA:#x}ull");
    println!("#define W42_IB_OFFSET\t{IB_OFFSET:#x}u");
    println!("#define W42_IB_DW\t{ib_dw}u");
    println!("#define W42_OUT_DW\t64u");
    println!("#define W42_OUT_VALUE\t42u");
    let p = |name: &str, d: &[u32]| {
        println!("static const uint32_t {name}[{}] = {{", d.len());
        for ch in d.chunks(6) {
            println!("\t{},", ch.iter().map(|x| format!("{x:#010x}")).collect::<Vec<_>>().join(", "));
        }
        println!("}};");
    };
    p("w42_shader", &dw[..shader_dw]);
    p("w42_ib", &dw[IB_OFFSET as usize / 4..]);
}
