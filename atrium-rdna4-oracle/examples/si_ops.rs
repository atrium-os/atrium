//! si_ops: real-shader stand-ins for gpusim's SIM_COMPUTE_KERNEL ops (stage
//! 5e, docs/spec/r9700-bare-metal.md §4.5), as a C header for the userspace
//! tests that run on silicon. gpusim's ops (engine/src/render.rs):
//!
//!   COPY  dst[i] = src[i]
//!   INC   dst[i] = src[i] + 1
//!   FILL  dst[i] = value
//!
//! Each shader runs one workgroup of 64 threads (two wave32 waves) and
//! touches dst[0..64) (and src[0..64) for COPY/INC), so a 4 KiB BO each is
//! enough. All three share one IB: the shader's address, src, dst and the
//! fill value travel as user SGPRs s[0:4]. The kernel picks each BO's GPU-VA
//! at VM_BIND, so the test patches the IB: the header carries the IB built
//! at one set of values and, for every dword that holds one, which and which
//! bits. Regenerate with
//!
//!     cargo run -q --example si_ops > ../atrium-gpu-amd/tests/si_ops.h
//!
//! The patch table is derived, not hand-written: every dword that differs
//! between builds at different values must match exactly one candidate
//! encoding at all four value sets, or the generator fails.
use atrium_rdna4_cmd::{emit_dispatch, Blob, Dispatch};
use atrium_rdna4_isa::encode;

fn inline_int(v: u32) -> u64 {
    assert!(v <= 64);
    128 + v as u64
}

#[derive(Clone, Copy)]
enum Op {
    Copy,
    Inc,
    Fill,
}

fn shader(op: Op) -> Vec<u32> {
    let mut sh: Vec<u32> = Vec::new();
    let e = |i: &str, enc: &str, f: &[(&str, u64)]| encode(i, enc, "default", f).unwrap();
    // v1 = v0 << 2            (byte offset of this thread's element)
    sh.extend(e("V_LSHLREV_B32", "ENC_VOP2", &[("VDST", 1), ("SRC0", inline_int(2)), ("VSRC1", 0)]));
    match op {
        Op::Copy | Op::Inc => {
            // global_load_b32 v2, v1, s[0:1]; wait for it
            sh.extend(e("GLOBAL_LOAD_B32", "ENC_VGLOBAL", &[("SADDR", 0), ("VADDR", 1), ("VDST", 2)]));
            sh.extend(e("S_WAIT_LOADCNT", "ENC_SOPP", &[("SIMM16", 0)]));
            if let Op::Inc = op {
                // v2 = 1 + v2
                sh.extend(e("V_ADD_NC_U32", "ENC_VOP2", &[("VDST", 2), ("SRC0", inline_int(1)), ("VSRC1", 2)]));
            }
        }
        Op::Fill => {
            // v2 = s4 (the value)
            sh.extend(e("V_MOV_B32", "ENC_VOP1", &[("VDST", 2), ("SRC0", 4)]));
        }
    }
    // global_store_b32 v1, v2, s[2:3]
    sh.extend(e("GLOBAL_STORE_B32", "ENC_VGLOBAL", &[("SADDR", 2), ("VADDR", 1), ("VSRC", 2)]));
    sh.extend(e("S_ENDPGM", "ENC_SOPP", &[]));
    sh
}

/// The IB for a shader at `code`, reading `src`, writing `dst`, fill `val`.
fn ib(code: u64, src: u64, dst: u64, val: u32) -> Vec<u32> {
    let mut ib = Blob::compute();
    ib.acquire_all();
    emit_dispatch(&mut ib, &Dispatch {
        shader_va: code,
        vgprs: 3,
        user_sgprs: vec![src as u32, (src >> 32) as u32, dst as u32, (dst >> 32) as u32, val],
        threads: [64, 1, 1],
        groups: [1, 1, 1],
        wave32: true,
        lds_bytes: 0,
        scratch: None,
    });
    ib.pad(8);
    ib.dw.clone()
}

/// (which: 0 code / 1 src / 2 dst / 3 value, shift, name).
const KINDS: [(u32, u32, &str); 9] = [
    (0, 0, "code lo"),
    (0, 32, "code hi"),
    (0, 8, "code >> 8"),
    (0, 40, "code >> 40"),
    (1, 0, "src lo"),
    (1, 32, "src hi"),
    (2, 0, "dst lo"),
    (2, 32, "dst hi"),
    (3, 0, "value"),
];

fn val(k: (u32, u32, &str), v: [u64; 4]) -> u32 {
    (v[k.0 as usize] >> k.1) as u32
}

fn main() {
    let sets: [[u64; 4]; 4] = [
        [0x1000_0000, 0x1000_2000, 0x1000_4000, 0x0000_0000],
        [0x12_3456_7000, 0x0abc_def0_1000, 0x0777_0000_3000, 0x1357_9bdf],
        [0x0f00_0010_0000, 0x0000_1234_5000, 0x0001_0020_0000, 0xfedc_ba98],
        [0x0000_7fff_f000, 0x0042_0000_0000, 0x0000_0001_0000, 0x0bad_cafe],
    ];
    let builds: Vec<Vec<u32>> = sets.iter().map(|s| ib(s[0], s[1], s[2], s[3] as u32)).collect();
    let base = &builds[0];
    for b in &builds {
        assert_eq!(b.len(), base.len());
    }
    let mut patches = Vec::new();
    for i in 0..base.len() {
        let differs = builds.iter().any(|b| b[i] != base[i]);
        let fits: Vec<_> =
            KINDS.iter().filter(|&&k| sets.iter().zip(&builds).all(|(&s, b)| b[i] == val(k, s))).collect();
        if differs {
            assert_eq!(fits.len(), 1, "IB dword {i} holds a value in no single known encoding");
            patches.push((i, *fits[0]));
        }
    }
    for w in 0..4 {
        assert!(patches.iter().any(|p| p.1 .0 == w), "IB must carry every parameter");
    }
    println!("/* Generated by atrium-rdna4-oracle/examples/si_ops.rs; do not edit. */");
    println!("/* gpusim's COPY/INC/FILL compute ops as real shaders: one workgroup of 64");
    println!(" * threads; dst[i] = src[i], src[i] + 1, or value, for i in [0, 64). */");
    println!("#define SIOPS_IB_DW\t{}u", base.len());
    println!("#define SIOPS_N\t\t64u");
    println!("#define SIOPS_NPATCH\t{}u", patches.len());
    let p = |name: &str, d: &[u32]| {
        println!("static const uint32_t {name}[{}] = {{", d.len());
        for ch in d.chunks(6) {
            println!("\t{},", ch.iter().map(|x| format!("{x:#010x}")).collect::<Vec<_>>().join(", "));
        }
        println!("}};");
    };
    p("siops_copy", &shader(Op::Copy));
    p("siops_inc", &shader(Op::Inc));
    p("siops_fill", &shader(Op::Fill));
    p("siops_ib", base);
    println!("/* IB dword `dw` = (uint32_t)(param[which] >> shift); params: 0 code VA,");
    println!(" * 1 src VA, 2 dst VA, 3 fill value. */");
    println!("static const struct {{ uint16_t dw; uint8_t which, shift; }} siops_patch[{}] = {{", patches.len());
    for (i, k) in &patches {
        println!("\t{{ {i}, {}, {} }},\t/* {} */", k.0, k.1, k.2);
    }
    println!("}};");
}
