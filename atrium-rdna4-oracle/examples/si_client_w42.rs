//! si_client_w42: the `write_42` oracle case as a C header for the stage
//! 5c-2 userspace test (atrium-gpu-amd/tests/si_client_test.c). The kernel
//! picks each BO's GPU-VA at VM_BIND, so the test patches the IB: the header
//! carries the IB built at one pair of addresses and, for every dword that
//! holds an address, which address and which bits. Regenerate with
//!
//!     cargo run -q --example si_client_w42 > ../atrium-gpu-amd/tests/si_w42.h
//!
//! The patch table is derived, not hand-written: every dword that differs
//! between builds at different addresses must match exactly one of the
//! candidate encodings, at three address pairs, or the generator fails.
use atrium_rdna4_oracle::cases::{write_42_at, IB_OFFSET};

fn build(code_va: u64, data_va: u64) -> (Vec<u32>, Vec<u32>) {
    let c = write_42_at(code_va, data_va);
    let code = &c.buffers[0].init;
    let n = IB_OFFSET as usize / 4 + c.ib.2 as usize;
    let dw: Vec<u32> = code[..n * 4].chunks(4).map(|b| u32::from_le_bytes(b.try_into().unwrap())).collect();
    let shader_dw = dw[..IB_OFFSET as usize / 4].iter().rposition(|&d| d != 0).map_or(0, |i| i + 1);
    (dw[..shader_dw].to_vec(), dw[IB_OFFSET as usize / 4..].to_vec())
}

/// (which: 0 code / 1 data, shift, name): dword = (va >> shift) as u32.
const KINDS: [(u32, u32, &str); 6] = [
    (0, 0, "code lo"),
    (0, 32, "code hi"),
    (0, 8, "code >> 8"),
    (0, 40, "code >> 40"),
    (1, 0, "data lo"),
    (1, 32, "data hi"),
];

fn val(k: (u32, u32, &str), code: u64, data: u64) -> u32 {
    ((if k.0 == 0 { code } else { data }) >> k.1) as u32
}

fn main() {
    let pairs = [
        (0x1000_0000u64, 0x1000_2000u64),
        (0x12_3456_7000, 0x0abc_def0_1000),
        (0x0f00_0010_0000, 0x0000_1234_5000),
    ];
    let base = pairs[0];
    let (shader, ib) = build(base.0, base.1);
    let builds: Vec<_> = pairs.iter().map(|&(c, d)| build(c, d)).collect();
    for b in &builds {
        assert_eq!(b.0, shader, "shader depends on its VA");
        assert_eq!(b.1.len(), ib.len());
    }
    let mut patches = Vec::new();
    for i in 0..ib.len() {
        let differs = builds.iter().any(|b| b.1[i] != ib[i]);
        let fits: Vec<_> = KINDS
            .iter()
            .filter(|&&k| pairs.iter().zip(&builds).all(|(&(c, d), b)| b.1[i] == val(k, c, d)))
            .collect();
        if differs {
            assert_eq!(fits.len(), 1, "IB dword {i} holds an address in no single known encoding");
            patches.push((i, *fits[0]));
        }
    }
    let has = |w: u32| patches.iter().any(|p| p.1 .0 == w);
    assert!(has(0) && has(1), "IB must name both the shader and the output");
    println!("/* Generated by atrium-rdna4-oracle/examples/si_client_w42.rs; do not edit. */");
    println!("/* write_42: 64 threads (wave32) store 42 at out[i]. */");
    println!("#define SIW42_IB_DW\t{}u", ib.len());
    println!("#define SIW42_OUT_DW\t64u");
    println!("#define SIW42_OUT_VALUE\t42u");
    println!("#define SIW42_NPATCH\t{}u", patches.len());
    let p = |name: &str, d: &[u32]| {
        println!("static const uint32_t {name}[{}] = {{", d.len());
        for ch in d.chunks(6) {
            println!("\t{},", ch.iter().map(|x| format!("{x:#010x}")).collect::<Vec<_>>().join(", "));
        }
        println!("}};");
    };
    p("siw42_shader", &shader);
    p("siw42_ib", &ib);
    println!("/* IB dword `dw` = (uint32_t)((which ? data_va : code_va) >> shift). */");
    println!("static const struct {{ uint16_t dw; uint8_t which, shift; }} siw42_patch[{}] = {{", patches.len());
    for (i, k) in &patches {
        println!("\t{{ {i}, {}, {} }},\t/* {} */", k.0, k.1, k.2);
    }
    println!("}};");
}
