BASE = {0: 0x1260, 1: 0xa000}

src = (lzma.open(sys.argv[1]).read() if sys.argv[1].endswith('.xz')
       else open(sys.argv[1], 'rb').read()).decode()
print('/* @generated by gen_gfx12_regs.py from Linux drivers/gpu/drm/amd/include/asic_reg/gc/')
print(' * gc_12_0_0_offset.h (Copyright Advanced Micro Devices, Inc.; MIT). Do not edit.')
